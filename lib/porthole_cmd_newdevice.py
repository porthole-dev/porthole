"""`porthole new-device` -- scaffold a profile for a device nobody has ported.

Scaffolds and seeds. It deliberately does NOT try to generate a working
deviceinfo, defconfig or DTS: every device differs, and a confidently wrong
auto-generated deviceinfo costs more than an empty one -- you debug the device
instead of the file.

What it can honestly answer, it answers: `fastboot getvar all` knows the slot
count and the current slot, and an existing pmaports device package knows the
screen size and the boot image offsets. Everything else is marked TODO with a
pointer to the playbook that resolves it.
"""
from __future__ import annotations

import difflib
